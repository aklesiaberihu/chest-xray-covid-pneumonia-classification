def show_sample_grid(filepaths, labels, class_names, title, save_name, n_per_class=4):
    n_classes = len(class_names)
    fig, axes = plt.subplots(n_classes, n_per_class,
                              figsize=(n_per_class * 2.8, n_classes * 2.8))
    fig.suptitle(title, fontsize=13, fontweight='bold', y=1.01)

    np.random.seed(SEED)
    for row, cls_name in enumerate(class_names):
        idxs = np.where(labels == row)[0]
        chosen = np.random.choice(idxs, size=min(n_per_class, len(idxs)), replace=False)
        for col, idx in enumerate(chosen):
            ax = axes[row, col]
            img = Image.open(filepaths[idx]).convert('RGB')
            ax.imshow(img)
            ax.set_xticks([])
            ax.set_yticks([])
            for spine in ax.spines.values():
                spine.set_visible(False)
            if col == 0:
                ax.set_title(cls_name, fontsize=11, fontweight='bold', loc='left', pad=4)

    plt.tight_layout()
    plt.savefig(os.path.join(EDA_DIR, save_name), dpi=300, bbox_inches='tight')
    plt.show()
    print(f"Saved: {save_name}")


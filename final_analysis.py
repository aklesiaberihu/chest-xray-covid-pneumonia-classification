stat_rows = []
for exp_name, exp_data in [('Exp1', exp1_internal), ('Exp2', exp2_internal)]:
    scratch_aucs, transfer_aucs = [], []
    for arch in ARCHITECTURES:
        s_name = next(m for d, m in EXP1_MODELS if arch in d and 'Scratch'  in d)
        t_name = next(m for d, m in EXP1_MODELS if arch in d and 'Transfer' in d)
        scratch_aucs.append(exp_data[s_name]['macro_auc'])
        transfer_aucs.append(exp_data[t_name]['macro_auc'])

    t_stat, p_val = ttest_rel(transfer_aucs, scratch_aucs)
    delta = float(np.mean(np.array(transfer_aucs) - np.array(scratch_aucs)))
    d     = cohen_d(transfer_aucs, scratch_aucs)
    sig   = 'Yes' if p_val < 0.05 else 'No'

    stat_rows.append({
        'Experiment':    exp_name,
        'Scratch_Mean':  round(np.mean(scratch_aucs), 4),
        'Transfer_Mean': round(np.mean(transfer_aucs), 4),
        'Delta':         round(delta, 4),
        't_stat':        round(t_stat, 4),
        'p_value':       round(p_val, 4),
        'Cohen_d':       round(d, 4),
        'Significant':   sig,
    })
    print(f'{exp_name}: Scratch={np.mean(scratch_aucs):.4f}  Transfer={np.mean(transfer_aucs):.4f}  delta={delta:+.4f}  p={p_val:.4f}  Cohen_d={d:.3f}  Sig={sig}')

df_stat = pd.DataFrame(stat_rows)

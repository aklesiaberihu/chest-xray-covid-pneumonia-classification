print('* Significance assessed at Bonferroni-adjusted α = 0.0125 (4 comparisons, family-wise α = 0.05)')
print('Only Exp2 ResNet50 Scratch vs CNN (p=0.0009) survives correction.')
print('Exp1 results (p=0.0237, p=0.0449) are nominally significant at uncorrected α=0.05 only.')

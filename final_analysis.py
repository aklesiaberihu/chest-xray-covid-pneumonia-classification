"""# Step 15 - mcnemar's test"""

def mcnemar_test(y_true, pred1, pred2):
    correct1 = (pred1 == y_true)
    correct2 = (pred2 == y_true)
    n01 = int(np.sum(~correct1 & correct2))
    n10 = int(np.sum(correct1 & ~correct2))
    if (n01 + n10) == 0:
        return np.nan, 1.0, n01, n10
    stat = (abs(n01 - n10) - 1)**2 / (n01 + n10)
    p    = 1 - chi2.cdf(stat, df=1)
    return round(float(stat), 4), round(float(p), 4), n01, n10

BONFERRONI_ALPHA = 0.0125  # 4 comparisons, family-wise α = 0.05

mcn_rows = []
print('McNemar Test (Yates continuity correction, Bonferroni α = 0.0125):')
print(f'{"Exp":<6} {"Model A":<25} {"Model B":<25} {"n01":>5} {"n10":>5} {"chi2":>8} {"p-val":>8} {"Sig*":>5}')
print('-' * 95)

for exp_name, exp_data in [('Exp1', exp1_internal), ('Exp2', exp2_internal)]:
    scratch_models  = [(d, m) for d, m in EXP1_MODELS if 'Scratch'  in d]
    transfer_models = [(d, m) for d, m in EXP1_MODELS if 'Transfer' in d]
    best_scratch    = max(scratch_models,  key=lambda x: exp_data[x[1]]['macro_auc'])
    best_transfer   = max(transfer_models, key=lambda x: exp_data[x[1]]['macro_auc'])
    best_overall    = max(EXP1_MODELS,     key=lambda x: exp_data[x[1]]['macro_auc'])
    y_true          = exp_data['cnn']['y_true']

    for a, b in [(best_scratch, best_transfer), (best_overall, ('CNN', 'cnn'))]:
        stat, p, n01, n10 = mcnemar_test(y_true, exp_data[a[1]]['y_pred'], exp_data[b[1]]['y_pred'])
        sig = 'Yes' if p < BONFERRONI_ALPHA else 'No'
        print(f'{exp_name:<6} {a[0]:<25} {b[0]:<25} {n01:>5} {n10:>5} {stat:>8} {p:>8} {sig:>5}')
        mcn_rows.append({'Exp': exp_name, 'Model_A': a[0], 'Model_B': b[0],
                         'n01': n01, 'n10': n10, 'chi2': stat, 'p_value': p,
                         'Significant_Bonferroni': sig})

df_mcn = pd.DataFrame(mcn_rows)
df_mcn.to_csv(os.path.join(OUT_DIR, '06_mcnemar_test.csv'), index=False)

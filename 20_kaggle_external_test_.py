"""# STEP 4: Load Kaggle Dataset"""

X_kaggle, y_kaggle = [], []

for cls_name, label in KAGGLE_CLASS_MAP.items():
    img_dir = os.path.join(KAGGLE_ROOT, cls_name, 'images')
    if not os.path.exists(img_dir):
        img_dir = os.path.join(KAGGLE_ROOT, cls_name)
    paths = sorted(glob.glob(os.path.join(img_dir, '*.png')))
    X_kaggle.extend(paths)
    y_kaggle.extend([label] * len(paths))
    print(f"  {cls_name}: {len(paths)} images")

X_kaggle = np.array(X_kaggle)
y_true   = np.array(y_kaggle)

print(f"\nTotal: {len(X_kaggle)} images")
print(f"Distribution: {np.bincount(y_true)}")

"""# STEP 5: Create TensorFlow Data Pipeline"""

def load_image(path, label):
    img = tf.io.read_file(path)
    img = tf.image.decode_image(img, channels=3, expand_animations=False)
    img = tf.image.resize(img, IMG_SIZE)
    img = tf.cast(img, tf.float32) / 255.0
    return img, label

kaggle_ds = (tf.data.Dataset.from_tensor_slices((X_kaggle, y_true))
             .map(load_image, num_parallel_calls=tf.data.AUTOTUNE)
             .batch(BATCH_SIZE)
             .prefetch(tf.data.AUTOTUNE))

y_bin = label_binarize(y_true, classes=range(N_CLASSES))
print('Pipeline ready.')

"""# STEP 6: Evaluate All 9 Models"""

PRED_DIR = os.path.join(OUT_DIR, 'predictions')
os.makedirs(PRED_DIR, exist_ok=True)

results = {}

for display_name, model_name in EXP1_MODELS:
    pred_path = os.path.join(PRED_DIR, f'{model_name}_y_pred.npy')
    prob_path = os.path.join(PRED_DIR, f'{model_name}_y_prob.npy')

    if os.path.exists(pred_path) and os.path.exists(prob_path):
        y_pred = np.load(pred_path)
        y_prob = np.load(prob_path)
        print(f'Loaded (cached): {display_name}')
    else:
        print(f'Running inference: {display_name}')
        model_path = os.path.join(THESIS_ROOT, 'experiments/exp1', model_name, 'best_model.keras')
        model      = keras.models.load_model(model_path)
        y_prob     = model.predict(kaggle_ds, verbose=0)
        y_pred     = np.argmax(y_prob, axis=1)
        np.save(pred_path, y_pred)
        np.save(prob_path, y_prob)
        del model
        gc.collect()

    model_aucs = []
    for i in range(N_CLASSES):
        fpr, tpr, _ = roc_curve(y_bin[:, i], y_prob[:, i])
        model_aucs.append(auc(fpr, tpr))
    macro_auc = float(np.mean(model_aucs))
    accuracy  = float(np.mean(y_pred == y_true))
    macro_f1  = float(f1_score(y_true, y_pred, average='macro'))

    results[model_name] = {
        'display_name' : display_name,
        'y_pred'       : y_pred,
        'y_prob'       : y_prob,
        'accuracy'     : accuracy,
        'macro_auc'    : macro_auc,
        'macro_f1'     : macro_f1,
        'per_class_auc': {CLASS_NAMES[i]: float(model_aucs[i]) for i in range(N_CLASSES)},
        'conf_mat'     : confusion_matrix(y_true, y_pred),
        'class_report' : classification_report(y_true, y_pred, target_names=CLASS_NAMES,
                                               output_dict=True, zero_division=0),
    }
    print(f'  Acc={accuracy:.4f}  AUC={macro_auc:.4f}  F1={macro_f1:.4f}')

print(f'\nAll results ready: {len(results)} models')


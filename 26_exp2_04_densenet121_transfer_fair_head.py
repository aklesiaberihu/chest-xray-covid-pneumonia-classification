"""# Step 6 - DenseNet121 Transfer model with FAIR (simple) head"""

def build_densenet121_transfer_fair(input_shape=(224, 224, 3), n_classes=3):
    base = keras.applications.DenseNet121(weights='imagenet', include_top=False, input_shape=input_shape)
    base.trainable = False
    x = layers.GlobalAveragePooling2D()(base.output)
    x = layers.Dropout(0.3)(x)
    outputs = layers.Dense(n_classes, activation='softmax')(x)
    return keras.Model(inputs=base.input, outputs=outputs, name='densenet121_transfer_fair')


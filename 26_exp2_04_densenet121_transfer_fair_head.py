class SaveHistoryEachEpoch(keras.callbacks.Callback):
    def __init__(self, path, initial_history=None):
        super().__init__()
        self.path = path
        self.data = initial_history or {}

    def on_epoch_end(self, epoch, logs=None):
        for k, v in (logs or {}).items():
            self.data.setdefault(k, []).append(float(v))
        with open(self.path, 'w') as f:
            json.dump(self.data, f, indent=2)


class MacroAUCCallback(keras.callbacks.Callback):
    def __init__(self, val_ds, n_classes):
        super().__init__()
        self.val_ds    = val_ds
        self.n_classes = n_classes

    def on_epoch_end(self, epoch, logs=None):
        from sklearn.metrics import roc_curve, auc
        y_true, y_prob = [], []
        for x_batch, y_batch in self.val_ds:
            y_prob.extend(self.model.predict(x_batch, verbose=0))
            y_true.extend(y_batch.numpy())
        y_true    = np.array(y_true)
        y_prob    = np.array(y_prob)
        y_bin     = label_binarize(y_true, classes=range(self.n_classes))
        macro_auc = np.mean([auc(*roc_curve(y_bin[:, i], y_prob[:, i])[:2])
                             for i in range(self.n_classes)])
        logs['val_auc'] = float(macro_auc)
        print(f'  val_auc: {macro_auc:.4f}', end='')


